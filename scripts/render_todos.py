"""Renders artifacts/TODOS.md from the frontmatter of the story, sprint, and blocker files.

A story's status, priority, estimate, and sprint live in its own file. TODOS.md shows them for the terminal, where
Dataview does not run, so it is generated and never edited by hand. Only the block between NEXT_ACTION_START and
NEXT_ACTION_END is written by hand, and a rerun keeps it byte for byte.

    python3 -I scripts/render_todos.py            rewrite artifacts/TODOS.md
    python3 -I scripts/render_todos.py --check    exit 1 if artifacts/TODOS.md is out of date
"""

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

POINTS = {"XS": 1, "S": 2, "M": 3, "L": 5}
# Work in flight first, finished work last.
STATUS_ORDER = ("In progress", "Blocked", "Reviewed", "Ready", "Not started", "Done")
CLOSED_STATUSES = ("Done", "Superseded")
OPEN_BLOCKER_STATUSES = ("open", "monitoring")
BACKLOG_LIMIT = 10
NEXT_ACTION_START = "<!-- next-action:start -->"
NEXT_ACTION_END = "<!-- next-action:end -->"
NO_NEXT_ACTION = "None."
INTRO = "How the work is planned: [[scrum-framework]]. All stories: [[User stories board]]. Index: [[Home]]."
HEADER = (
    "<!-- Generated by scripts/render_todos.py from the story, sprint, and blocker frontmatter. "
    "Edit those files and run the script. Only the Next action block is hand-written. -->"
)


@dataclass(frozen=True)
class Story:
    us_id: str
    title: str
    status: str
    priority: str
    estimate: str
    sprint: Optional[int]
    epic_stem: str
    kind: str
    stem: str

    @property
    def points(self) -> int:
        return POINTS[self.estimate]

    @property
    def epic_id(self) -> str:
        return re.match(r"EP-\d+", self.epic_stem).group(0)


@dataclass(frozen=True)
class Sprint:
    number: int
    start: str
    end: str
    status: str
    goal: str
    stem: str


@dataclass(frozen=True)
class Blocker:
    bl_id: str
    stem: str
    title: str
    status: str
    severity: str


def parse_frontmatter(text: str, source: str) -> dict:
    """Reads the `key: value` lines of the leading --- block. List values stay as raw text."""
    lines = text.split("\n")
    if not lines or lines[0] != "---":
        raise ValueError(f"{source}: no frontmatter")
    fields = {}
    for line in lines[1:]:
        if line == "---":
            return fields
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):(?: (.*))?$", line)
        if match:
            fields[match.group(1)] = unquote((match.group(2) or "").strip())
    raise ValueError(f"{source}: frontmatter is not closed")


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return re.sub(r"\\(.)", r"\1", value[1:-1])
    return value


def require(fields: dict, keys: tuple, source: str) -> None:
    missing = [key for key in keys if not fields.get(key)]
    if missing:
        raise ValueError(f"{source}: missing {', '.join(missing)}")


def parse_story(path: Path) -> Story:
    fields = parse_frontmatter(path.read_text(encoding="utf-8"), str(path))
    require(fields, ("us_id", "title", "status", "priority", "estimate"), str(path))
    if fields["estimate"] not in POINTS:
        raise ValueError(f"{path}: estimate {fields['estimate']!r} is not one of {', '.join(POINTS)}")
    if fields["status"] not in STATUS_ORDER + ("Superseded",):
        raise ValueError(f"{path}: status {fields['status']!r} is not a known status")
    epic = re.search(r"EP-\d+[^\]|]*", fields.get("epic", ""))
    return Story(
        us_id=fields["us_id"],
        title=fields["title"],
        status=fields["status"],
        priority=fields["priority"],
        estimate=fields["estimate"],
        sprint=parse_sprint_number(fields.get("sprint", ""), path),
        epic_stem=epic.group(0) if epic else "",
        kind=fields.get("kind", "story"),
        stem=path.stem,
    )


def parse_sprint_number(value: str, path: Path) -> Optional[int]:
    if not value:
        return None
    if not value.isdigit():
        raise ValueError(f"{path}: sprint {value!r} is not a number")
    return int(value)


def parse_sprint(path: Path) -> Sprint:
    text = path.read_text(encoding="utf-8")
    fields = parse_frontmatter(text, str(path))
    require(fields, ("sprint", "start_date", "end_date", "status"), str(path))
    goal = re.search(r"^## Sprint goal\n+([^\n]+)", text, re.M)
    return Sprint(
        number=int(fields["sprint"]),
        start=fields["start_date"],
        end=fields["end_date"],
        status=fields["status"],
        goal=goal.group(1).strip() if goal else "",
        stem=path.stem,
    )


def parse_blocker(path: Path) -> Blocker:
    text = path.read_text(encoding="utf-8")
    fields = parse_frontmatter(text, str(path))
    require(fields, ("status", "severity"), str(path))
    heading = re.search(r"^# (.+)$", text, re.M)
    return Blocker(
        bl_id=re.match(r"BL-\d+", path.stem).group(0),
        stem=path.stem,
        title=heading.group(1).strip() if heading else path.stem,
        status=fields["status"],
        severity=fields["severity"],
    )


def current_sprint(sprints: list) -> Optional[Sprint]:
    """The active sprint, or else the lowest-numbered sprint still in planning."""
    for status in ("active", "planning"):
        candidates = sorted((s for s in sprints if s.status == status), key=lambda s: s.number)
        if candidates:
            return candidates[0]
    return None


def story_key(story: Story) -> tuple:
    return (priority_rank(story.priority), int(story.us_id.split("-")[1]))


def priority_rank(priority: str) -> int:
    return int(priority[1:]) if re.fullmatch(r"P\d", priority) else 9


def link(stem: str, label: str) -> str:
    return f"[[{stem}|{label}]]"


def render_sprint(sprint: Optional[Sprint], stories: list) -> list:
    if sprint is None:
        return ["## Current sprint", "", "No sprint is active or in planning."]
    picked = [s for s in stories if s.sprint == sprint.number]
    done_points = sum(s.points for s in picked if s.status == "Done")
    lines = [f"## Current sprint: Sprint {sprint.number}, {sprint.start} to {sprint.end}", ""]
    lines.append(f"**Goal:** {sprint.goal}" if sprint.goal else "**Goal:** not written yet.")
    lines.append("")
    lines.append(f"**Sprint file:** {link(sprint.stem, f'SPR-{sprint.number:03d}')}")
    lines.append("")
    lines.append(
        f"**Status:** {sprint.status}. {sum(s.points for s in picked)} points picked, {done_points} done."
    )
    if not picked:
        lines += ["", "No story has this sprint yet."]
    for status in STATUS_ORDER:
        for story in sorted((s for s in picked if s.status == status), key=story_key):
            lines += ["", f"### {story.status} - {story.us_id} {story.title}", ""]
            lines.append(f"**Story:** {link(story.stem, story.us_id)}. {describe(story)}")
    return lines


def describe(story: Story) -> str:
    parts = [story.priority, f"{story.estimate} ({story.points} points)"]
    if story.epic_stem:
        parts.append(link(story.epic_stem, story.epic_id))
    if story.kind != "story":
        parts.append(story.kind)
    return ", ".join(parts) + "."


def render_backlog(stories: list) -> list:
    backlog = sorted((s for s in stories if s.sprint is None and s.status not in CLOSED_STATUSES), key=story_key)
    lines = ["## Product backlog", "", f"{len(backlog)} stories. The top {min(BACKLOG_LIMIT, len(backlog))} by priority:", ""]
    lines += [
        f"- {link(s.stem, s.us_id)}, {s.priority}, {s.estimate}, {s.status}. {s.title}" for s in backlog[:BACKLOG_LIMIT]
    ]
    return lines


def render_blockers(blockers: list) -> list:
    open_blockers = sorted(
        (b for b in blockers if b.status in OPEN_BLOCKER_STATUSES),
        key=lambda b: (priority_rank(b.severity), int(b.bl_id.split("-")[1])),
    )
    lines = ["## Open blockers", ""]
    lines += [f"- {link(b.stem, b.bl_id)}, {b.severity}, {b.status}. {b.title}" for b in open_blockers]
    if not open_blockers:
        lines.append("None.")
    return lines + ["", "All blockers: [[Blockers board]]."]


def render(stories: list, sprints: list, blockers: list, next_action: str) -> str:
    sections = [
        ["# TODOS", "", HEADER, "", INTRO],
        ["## Next action", "", NEXT_ACTION_START, next_action.strip("\n"), NEXT_ACTION_END],
        render_sprint(current_sprint(sprints), stories),
        render_backlog(stories),
        render_blockers(blockers),
    ]
    return "\n\n".join("\n".join(section) for section in sections) + "\n"


def extract_next_action(todos_text: str) -> str:
    match = re.search(re.escape(NEXT_ACTION_START) + r"\n(.*?)\n" + re.escape(NEXT_ACTION_END), todos_text, re.S)
    return match.group(1) if match else NO_NEXT_ACTION


def load(vault: Path) -> tuple:
    stories = [parse_story(p) for p in sorted((vault / "docs/stories").glob("US-*.md"))]
    sprints = [parse_sprint(p) for p in sorted((vault / "docs/sprints").glob("SPR-*.md"))]
    blockers = [parse_blocker(p) for p in sorted((vault / "docs/blockers").glob("BL-*.md"))]
    return stories, sprints, blockers


def render_vault(vault: Path) -> str:
    todos = vault / "TODOS.md"
    next_action = extract_next_action(todos.read_text(encoding="utf-8")) if todos.exists() else NO_NEXT_ACTION
    return render(*load(vault), next_action)


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description="Render artifacts/TODOS.md from the story frontmatter.")
    parser.add_argument("--vault", type=Path, default=Path(__file__).resolve().parents[1] / "artifacts")
    parser.add_argument("--check", action="store_true", help="exit 1 if TODOS.md is out of date; write nothing")
    args = parser.parse_args(argv)
    todos = args.vault / "TODOS.md"
    rendered = render_vault(args.vault)
    current = todos.read_text(encoding="utf-8") if todos.exists() else None
    if args.check:
        if current != rendered:
            print(f"{todos} is out of date. Run: python3 -I scripts/render_todos.py", file=sys.stderr)
            return 1
        return 0
    if current != rendered:
        todos.write_text(rendered, encoding="utf-8")
        print(f"wrote {todos}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
